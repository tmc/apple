//go:build ignore

// Gentable turns opschema.json, dumped from the coremltools runtime registry by
// dumpops.py, into table.gen.go. Run it from the opschema package directory.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
)

type schema struct {
	CoremltoolsVersion string                       `json:"coremltools_version"`
	CoremltoolsCommit  string                       `json:"coremltools_commit"`
	OpSets             map[string]map[string]jsonOp `json:"opsets"`
}

type jsonOp struct {
	Type    string              `json:"type"`
	Params  []jsonParam         `json:"params"`
	Domains map[string][]string `json:"domains"`
}

type jsonParam struct {
	Name     string   `json:"name"`
	Kind     string   `json:"kind"`
	Const    bool     `json:"const"`
	Optional bool     `json:"optional"`
	DomainID string   `json:"domain_id"`
	Domain   []string `json:"domain"`
}

var kinds = map[string]string{
	"tensor":             "KindTensor",
	"list":               "KindList",
	"listortensorordict": "KindListOrTensorOrDict",
	"tuple":              "KindTuple",
	"state":              "KindState",
	"pyfunc":             "KindPyFunc",
	"internal":           "KindInternal",
}

func main() {
	log.SetFlags(0)
	log.SetPrefix("gentable: ")
	data, err := os.ReadFile("opschema.json")
	if err != nil {
		log.Fatal(err)
	}
	var s schema
	if err := json.Unmarshal(data, &s); err != nil {
		log.Fatal(err)
	}
	if len(s.OpSets) == 0 {
		log.Fatal("no opsets in opschema.json")
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen/gentable.go from opschema.json. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "// coremltools %s (%s)\n\n", s.CoremltoolsVersion, s.CoremltoolsCommit)
	fmt.Fprintf(&b, "package opschema\n\n")
	fmt.Fprintf(&b, "var opsets = map[string]map[string]*Op{\n")
	for _, opset := range sortedKeys(s.OpSets) {
		ops := s.OpSets[opset]
		if len(ops) == 0 {
			log.Fatalf("opset %s has no ops", opset)
		}
		fmt.Fprintf(&b, "%q: {\n", opset)
		for _, name := range sortedKeys(ops) {
			op := ops[name]
			fmt.Fprintf(&b, "%q: {Type: %q, Params: []Param{\n", name, name)
			for _, p := range op.Params {
				kind, ok := kinds[p.Kind]
				if !ok {
					log.Fatalf("op %s input %s: unknown kind %q", name, p.Name, p.Kind)
				}
				fmt.Fprintf(&b, "{Name: %q, Kind: %s", p.Name, kind)
				if p.Const {
					fmt.Fprintf(&b, ", Const: true")
				}
				if p.Optional {
					fmt.Fprintf(&b, ", Optional: true")
				}
				if p.DomainID != "" {
					fmt.Fprintf(&b, ", DomainID: %q", p.DomainID)
				}
				if len(p.Domain) > 0 {
					fmt.Fprintf(&b, ", Domain: %s", domainLit(p.Domain))
				}
				fmt.Fprintf(&b, "},\n")
			}
			fmt.Fprintf(&b, "}")
			if len(op.Domains) > 0 {
				fmt.Fprintf(&b, ", Domains: map[string][]DataType{\n")
				for _, id := range sortedKeys(op.Domains) {
					fmt.Fprintf(&b, "%q: %s,\n", id, domainLit(op.Domains[id]))
				}
				fmt.Fprintf(&b, "}")
			}
			fmt.Fprintf(&b, "},\n")
		}
		fmt.Fprintf(&b, "},\n")
	}
	fmt.Fprintf(&b, "}\n\n")

	// Ops recorded for at least one opset. An op outside this set is one the
	// table says nothing about, which is not the same as an op that does not
	// exist: the dump covers only the ops we emit.
	all := map[string]bool{}
	for _, ops := range s.OpSets {
		for name := range ops {
			all[name] = true
		}
	}
	fmt.Fprintf(&b, "var registered = map[string]bool{\n")
	for _, name := range sortedKeys(all) {
		fmt.Fprintf(&b, "%q: true,\n", name)
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("table.gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func domainLit(ts []string) string {
	var b bytes.Buffer
	b.WriteString("[]DataType{")
	for i, t := range ts {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", t)
	}
	b.WriteString("}")
	return b.String()
}

func sortedKeys[V any](m map[string]V) []string {
	ks := make([]string, 0, len(m))
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}
